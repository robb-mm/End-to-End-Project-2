USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
USE DATABASE SNOWFLAKE_LEARNING_DB;

CREATE OR REPLACE SCHEMA SALES_ANALYSIS;

CREATE OR REPLACE STORAGE INTEGRATION SALES_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::756118984626:role/sales_role'
  STORAGE_ALLOWED_LOCATIONS = ('s3://sales-data-bucket.rob/data/');

STORAGE_AWS_IAM_USER_ARN;
DESC INTEGRATION SALES_INT;

CREATE OR REPLACE STAGE SALES_STAGE
STORAGE_INTEGRATION = SALES_INT
URL= 's3://sales-data-bucket.rob/data/';

ls @SALES_STAGE;


CREATE OR REPLACE TABLE SALES_DATA
(
    DATE DATE,
    PRODUCT STRING,
    REGION STRING,
    UNITS_SOLD INTEGER,
    UNIT_PRICE DECIMAL(10,2),
    SALES DECIMAL(10,2)
);

CREATE OR REPLACE PIPE SALES_PIPE 
AUTO_INGEST = TRUE AS
COPY INTO SALES_DATA
FROM (SELECT  $1 AS DATE,
              $2 AS PRODUCT,
              $3 AS REGION,
              $4 AS UNITS_SOLD,
              $5 AS UNIT_PRICE,
              $6 AS SALES
        FROM  @SALES_STAGE)
FILE_FORMAT = (TYPE = 'CSV' SKIP_HEADER=1 FIELD_OPTIONALLY_ENCLOSED_BY ='"');

SELECT SYSTEM$PIPE_STATUS('SALES_PIPE');

SHOW PIPES;

